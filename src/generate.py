from pathlib import Path
from datetime import datetime, timezone
import json, os, re, shutil, subprocess, hashlib, html

from models import build_catalog

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "output"
today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
target = OUT / today
target.mkdir(parents=True, exist_ok=True)

count = int(os.getenv("MODEL_COUNT", "5"))
catalog = build_catalog(int(datetime.now(timezone.utc).strftime("%j")))
models = catalog[:max(1, min(count, len(catalog)))]

openscad = shutil.which("openscad")
manifest = {
    "generated_at_utc": datetime.now(timezone.utc).isoformat(),
    "date": today,
    "printer_target": "Bambu Lab P2S Combo",
    "model_count": len(models),
    "status": "prepared_for_manual_review",
    "models": []
}

def safe(s):
    return re.sub(r"[^a-z0-9-]+", "-", s.lower()).strip("-")

for i, model in enumerate(models, start=1):
    folder = target / f"{i:02d}-{model.slug}"
    folder.mkdir(exist_ok=True)
    scad_path = folder / f"{model.slug}.scad"
    stl_path = folder / f"{model.slug}.stl"
    scad_path.write_text(model.scad, encoding="utf-8")

    export_status = "openscad_not_installed"
    stl_bytes = 0
    if openscad:
        proc = subprocess.run(
            [openscad, "-o", str(stl_path), str(scad_path)],
            capture_output=True, text=True, timeout=180
        )
        if proc.returncode == 0 and stl_path.exists() and stl_path.stat().st_size > 500:
            export_status = "stl_exported_basic_file_check_passed"
            stl_bytes = stl_path.stat().st_size
        else:
            export_status = "stl_export_failed"
            (folder / "openscad_error.txt").write_text(
                (proc.stdout or "") + "\n" + (proc.stderr or ""), encoding="utf-8"
            )

    description = f"""## {model.title}

{model.description}

### Druckhinweise
- Zielgerät: Bambu Lab P2S Combo
- Datei: STL-Geometrie; Druckprofil und Material in Bambu Studio selbst festlegen.
- Vor Veröffentlichung slicen und einen realen Testdruck durchführen.

### Hinweise
{model.caution}

Dies ist ein parametrischer Erstentwurf und kein technisch zertifiziertes Produkt.
"""
    (folder / "makerworld_description.md").write_text(description, encoding="utf-8")
    (folder / "tags.txt").write_text(", ".join(model.tags), encoding="utf-8")

    digest = hashlib.sha256(scad_path.read_bytes()).hexdigest()
    manifest["models"].append({
        "number": i, "slug": model.slug, "title": model.title,
        "folder": str(folder.relative_to(OUT)),
        "scad": str(scad_path.relative_to(OUT)),
        "stl": str(stl_path.relative_to(OUT)) if stl_path.exists() else None,
        "stl_status": export_status, "stl_bytes": stl_bytes,
        "sha256_scad": digest, "tags": model.tags,
        "caution": model.caution,
        "publication": "manual_review_required"
    })

(target / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")

rows = []
for item in manifest["models"]:
    stl_link = f'<a href="{html.escape(item["stl"])}">STL</a>' if item["stl"] else "STL nicht erzeugt"
    rows.append(f"<tr><td>{item['number']}</td><td>{html.escape(item['title'])}</td><td>{html.escape(item['stl_status'])}</td><td>{stl_link}</td><td><a href='{html.escape(item['folder'])}/makerworld_description.md'>Beschreibung</a></td></tr>")
page = f"""<!doctype html><html lang="de"><meta charset="utf-8"><meta name="viewport" content="width=device-width">
<title>MakerWorld Autopilot {today}</title>
<style>body{{font:16px system-ui;max-width:1000px;margin:2rem auto;padding:0 1rem}}table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #ddd;padding:.65rem;text-align:left}}th{{background:#eee}}.note{{padding:1rem;background:#fff4d6}}</style>
<h1>MakerWorld Autopilot</h1><p>Erzeugt: {today} · Zielgerät: Bambu Lab P2S Combo</p>
<div class="note"><b>Manuelle Qualitätsfreigabe erforderlich:</b> Diese Übersicht bestätigt keine Festigkeit, Maßhaltigkeit oder MakerWorld-Regelkonformität. Vor Veröffentlichung slicen und testdrucken.</div>
<table><thead><tr><th>#</th><th>Modell</th><th>Exportstatus</th><th>STL</th><th>Text</th></tr></thead><tbody>{''.join(rows)}</tbody></table>
<p>Gesamtstatus: vorbereitet, nicht automatisch veröffentlicht.</p></html>"""
(target / "dashboard.html").write_text(page, encoding="utf-8")


